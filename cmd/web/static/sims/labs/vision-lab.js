      const why = outcome === 'same'
        ? tr(`Neither fell by ${fmt(DROP * 100)} points or more on this run.`, `Tidak ada yang turun ${fmt(DROP * 100)} poin atau lebih pada percobaan ini.`)
        : tr('The network never saw such images in training, so what it learned does not carry over.', 'Network tidak pernah melihat gambar seperti itu saat training, jadi yang ia pelajari tidak ikut berlaku.');
      quizShift.reveal(outcome, `${list} ${why}`);
