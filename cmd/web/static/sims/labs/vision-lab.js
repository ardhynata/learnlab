  // Where everything goes for a canvas of width W and height H (H 0 = as tall as it needs, for a narrow screen).
  function layout(W, H) {
    const compact = W < 560;
    const cols = compact ? 4 : W >= 760 ? 8 : 6;
    const cellW = (W - 2 * PAD) / cols;
    const img = Math.max(34, Math.min(64, Math.floor(cellW - 8)));
    const cellH = img + 30;
    const rows = compact ? 4 : Math.max(2, Math.min(6, Math.floor((H * 0.44 - TITLE_H) / cellH)));
    const gridH = TITLE_H + rows * cellH;
    const bTop = gridH + 8;
    const F = filterCount();
    const dense = currentModelKind() === 'dense';
    const big = Math.floor(Math.min(compact ? W * 0.42 : W * 0.3, 150, compact ? 150 : Math.max(60, H - bTop - 100)));
    const picture = { x: PAD, y: bTop + TITLE_H, s: big };
    const fx = compact ? PAD : PAD + big + 18;
    const fw = W - PAD - fx;
    const perRow = compact ? Math.min(F, 4) : F;
    const colW = fw / Math.max(1, perRow);
    const kc = Math.max(8, Math.min(18, Math.floor(colW / 4)));
    const overhead = 12 + 3 * kc + 4 + 12 + 4 + 12;
    const groups = compact ? Math.ceil(F / 4) : 1;
    let mc = Math.min(14, (colW - 4) / (dense ? 12 : 10));
    let groupH;
    if (dense) groupH = 12 + 12 * mc + 8 + 12 + 30;
    else groupH = overhead + 20 * mc;
    if (!compact) {
      const availH = H - (bTop + TITLE_H) - 6;
      const limit = dense ? (availH - 12 - 8 - 12 - 30) / 12 : (availH - overhead) / 20;
      mc = Math.max(3, Math.min(mc, limit));
      groupH = dense ? 12 + 12 * mc + 8 + 12 + 30 : overhead + 20 * mc;
    }
    const filtersTop = compact ? picture.y + big + 66 : picture.y;
    const need = compact ? Math.ceil(filtersTop + TITLE_H + groups * (groupH + 8) + PAD) : H;
    return { compact, cols, rows, cellW, img, cellH, gridH, bTop, picture, fx, fw, F, perRow, colW, kc, mc, groupH, filtersTop, need, dense, count: Math.min(MAX_GRID, cols * rows) };
  }

