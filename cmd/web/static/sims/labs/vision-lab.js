  function drawFilters(ctx, L, t, bg, model, img) {
    const posRgb = cssRgb(clusterColor(6), [95, 138, 26]), negRgb = cssRgb(clusterColor(5), [162, 79, 176]), accRgb = cssRgb(clusterColor(4), [26, 130, 192]);
    ctx.textAlign = 'left'; ctx.fillStyle = t.ink; ctx.font = '600 12px system-ui, sans-serif';
    const dense = model.kind === 'dense';
    const classIndex = shown.labels[chosen] ?? 0;
    const view = filterView(model, img, classIndex);
    const titleY = L.compact ? L.filtersTop + 12 : L.bTop + 14;
    const title = dense
      ? tr(`First hidden units: weights on all 144 pixels (network for ${shapeName(task.classes[classIndex])})`, `Hidden unit pertama: weight pada 144 piksel (network untuk ${shapeName(task.classes[classIndex])})`)
      : tr('Learned filters (3×3) and feature maps of the chosen image', 'Filter hasil belajar (3×3) dan feature map gambar terpilih');
    ctx.fillText(fitText(ctx, title, L.fw), L.fx, titleY);
    const top0 = (L.compact ? L.filtersTop : L.picture.y) + (L.compact ? 20 : 0);
    const items = dense ? view.units : view.filters;
    const label = (text, x, y) => { ctx.font = '11px system-ui, sans-serif'; ctx.fillStyle = t.muted; ctx.fillText(fitText(ctx, text, L.fw), x, y); };
    // brightest value over all maps of this picture, so a weak filter looks weak
    const maxAct = dense ? 1 : Math.max(1e-6, ...view.filters.map(f => Math.max(...f.activated.data)));
    items.forEach((it, f) => {
      const group = Math.floor(f / L.perRow), col = f % L.perRow;
      const x0 = L.fx + col * L.colW + 2, gy = top0 + group * (L.groupH + 8);
      if (dense) {
        const maxW = Math.max(1e-6, ...it.weights.map(Math.abs));
        if (col === 0) label(tr('Weights, one per pixel (12×12)', 'Weight, satu per piksel (12×12)'), x0, gy + 10);
        blit(ctx, 12, 12, k => { const w = it.weights[k] / maxW; return mix(bg, w >= 0 ? posRgb : negRgb, Math.abs(w)); }, x0, gy + 14, L.mc, L.mc);
        const by = gy + 14 + 12 * L.mc + 8;
        if (col === 0) label(tr('Output for this image', 'Output untuk gambar ini'), x0, by + 8);
        const bw = Math.max(4, L.colW - 8), frac = Math.min(1, it.output / Math.max(1, ...items.map(u => u.output)));
        ctx.fillStyle = t.grid; ctx.fillRect(x0, by + 14, bw, 10);
        ctx.fillStyle = clusterColor(4); ctx.fillRect(x0, by + 14, bw * frac, 10);
        ctx.fillStyle = t.ink; ctx.font = '10px system-ui, sans-serif'; ctx.fillText(fmt(it.output, { digits: 2 }), x0, by + 36);
        return;
      }
      // CNN: kernel, feature map after ReLU, pooled map
      let y = gy;
      if (col === 0) label(tr('Filter (3×3 weights)', 'Filter (weight 3×3)'), x0, y + 10);
      y += 12;
      const maxK = Math.max(1e-6, ...it.kernel.map(Math.abs)), kc = L.kc;
      blit(ctx, 3, 3, k => { const w = it.kernel[k] / maxK; return mix(bg, w >= 0 ? posRgb : negRgb, Math.abs(w)); }, x0, y, kc, kc);
      if (kc >= 20) {
        ctx.font = '10px system-ui, sans-serif'; ctx.textAlign = 'center'; ctx.fillStyle = t.ink;
        it.kernel.forEach((w, k) => ctx.fillText(fmt(w, { digits: 1 }), x0 + (k % 3) * kc + kc / 2, y + Math.floor(k / 3) * kc + kc / 2 + 3));
        ctx.textAlign = 'left';
      }
      ctx.strokeStyle = t.grid; ctx.lineWidth = 1; ctx.strokeRect(x0 - 0.5, y - 0.5, 3 * kc + 1, 3 * kc + 1);
      ctx.font = '600 11px system-ui, sans-serif'; ctx.fillStyle = t.ink; ctx.fillText(String(f + 1), x0 + 3 * kc + 6, y + 11);
      y += 3 * kc + 4;
      if (col === 0) label(tr('Feature map after ReLU (10×10)', 'Feature map setelah ReLU (10×10)'), x0, y + 10);
      y += 12;
      blit(ctx, 10, 10, k => mix(bg, accRgb, it.activated.data[k] / maxAct), x0, y, L.mc, L.mc);
      ctx.strokeStyle = t.grid; ctx.strokeRect(x0 - 0.5, y - 0.5, 10 * L.mc + 1, 10 * L.mc + 1);
      y += 10 * L.mc + 4;
      if (col === 0) label(tr('After max pooling (5×5)', 'Setelah max pooling (5×5)'), x0, y + 10);
      y += 12;
      blit(ctx, 5, 5, k => mix(bg, accRgb, it.pooled.data[k] / maxAct), x0, y, L.mc * 2, L.mc * 2);
      ctx.strokeRect(x0 - 0.5, y - 0.5, 10 * L.mc + 1, 10 * L.mc + 1);
    });
  }

