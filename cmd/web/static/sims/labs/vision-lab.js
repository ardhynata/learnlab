function prepare(canvas) {
  const { width, height } = canvas.getBoundingClientRect();
  const ratio = window.devicePixelRatio || 1;
  canvas.width = Math.max(1, Math.round(width * ratio)); canvas.height = Math.max(1, Math.round(height * ratio));
  const ctx = canvas.getContext('2d');
  ctx.setTransform(ratio, 0, 0, ratio, 0, 0);
  return { ctx, width, height };
}

function cssRgb(color, fallback) {
  const hex = /^#([0-9a-f]{6})$/i.exec(color || '');
  if (hex) { const n = parseInt(hex[1], 16); return [(n >> 16) & 255, (n >> 8) & 255, n & 255]; }
  const short = /^#([0-9a-f]{3})$/i.exec(color || '');
  if (short) return short[1].split('').map(c => parseInt(c + c, 16));
  const rgb = /^rgba?\(\s*(\d+)[,\s]+(\d+)[,\s]+(\d+)/.exec(color || '');
  return rgb ? [Number(rgb[1]), Number(rgb[2]), Number(rgb[3])] : fallback;
}
const mix = (a, b, t) => [0, 1, 2].map(i => Math.round(a[i] + (b[i] - a[i]) * Math.max(0, Math.min(1, t))));

const tile = typeof document !== 'undefined' ? document.createElement('canvas') : null;
// Draws a w x h grid of cells, each cw x ch, from rgbAt(index) -> [r, g, b], with crisp edges.
function blit(ctx, w, h, rgbAt, x, y, cw, ch) {
  tile.width = w; tile.height = h;
  const tctx = tile.getContext('2d');
  const data = tctx.createImageData(w, h);
  for (let i = 0; i < w * h; i++) { const [r, g, b] = rgbAt(i); data.data[i * 4] = r; data.data[i * 4 + 1] = g; data.data[i * 4 + 2] = b; data.data[i * 4 + 3] = 255; }
  tctx.putImageData(data, 0, 0);
  ctx.save(); ctx.imageSmoothingEnabled = false;
  ctx.drawImage(tile, x, y, w * cw, h * ch);
  ctx.restore();
}

function fitText(ctx, text, maxWidth) {
  if (ctx.measureText(text).width <= maxWidth) return text;
  let s = text;
  while (s.length > 1 && ctx.measureText(`${s}…`).width > maxWidth) s = s.slice(0, -1);
  return `${s}…`;
}

