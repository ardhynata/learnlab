// Everything is generated by the lab: no photos or image files are loaded. Training runs in slices of about 10 ms per animation
// frame, a few mini-batches of the CNN (or one small network of the dense baseline) at a time, so the page stays responsive and
// Pause answers within a frame. The lab starts untrained: nothing trains until the learner presses Train or Compare. The math is
// in ml/vision.js (network, pictures, augmentation) and ml/visionlab.js (task, runs, cache, evaluation, true boxes); this file
